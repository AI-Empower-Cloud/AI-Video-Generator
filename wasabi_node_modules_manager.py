#!/usr/bin/env python3
"""
Wasabi Node Modules Manager for AI Video Generator
Handles uploading, downloading, and syncing node_modules to/from Wasabi cloud storage
"""

import os
import sys
import boto3
import json
import tarfile
import hashlib
import shutil
from pathlib import Path
from dotenv import load_dotenv
from datetime import datetime
import argparse
import subprocess
import tempfile

class WasabiNodeModulesManager:
    def __init__(self):
        # Load environment variables
        load_dotenv('.env.wasabi')
        
        self.access_key = os.getenv('WASABI_ACCESS_KEY')
        self.secret_key = os.getenv('WASABI_SECRET_KEY')
        self.bucket_name = os.getenv('WASABI_BUCKET', 'ai-video-generator-content')
        self.region = os.getenv('WASABI_REGION', 'us-east-1')
        self.endpoint = os.getenv('WASABI_ENDPOINT', 'https://s3.wasabisys.com')
        
        if not self.access_key or not self.secret_key:
            print("❌ Error: WASABI_ACCESS_KEY and WASABI_SECRET_KEY must be set in .env.wasabi")
            print("\n📝 Please run: ./configure_wasabi_keys.sh")
            sys.exit(1)
        
        # Initialize S3 client
        self.s3 = boto3.client(
            's3',
            endpoint_url=self.endpoint,
            aws_access_key_id=self.access_key,
            aws_secret_access_key=self.secret_key,
            region_name=self.region
        )
        
        print(f"🚀 Connected to Wasabi bucket: {self.bucket_name}")
    
    def calculate_package_json_hash(self, package_json_path):
        """Calculate hash of package.json for cache validation"""
        try:
            with open(package_json_path, 'rb') as f:
                content = f.read()
                return hashlib.md5(content).hexdigest()
        except FileNotFoundError:
            return None
    
    def get_project_info(self, project_path):
        """Extract project name and version from package.json"""
        package_json_path = os.path.join(project_path, 'package.json')
        try:
            with open(package_json_path, 'r') as f:
                package_data = json.load(f)
                return {
                    'name': package_data.get('name', 'unknown'),
                    'version': package_data.get('version', '1.0.0'),
                    'hash': self.calculate_package_json_hash(package_json_path)
                }
        except (FileNotFoundError, json.JSONDecodeError):
            return {
                'name': os.path.basename(project_path),
                'version': '1.0.0',
                'hash': None
            }
    
    def compress_node_modules(self, node_modules_path, output_path):
        """Compress node_modules directory to tar.gz"""
        print(f"📦 Compressing {node_modules_path}...")
        
        with tarfile.open(output_path, 'w:gz') as tar:
            tar.add(node_modules_path, arcname='node_modules')
        
        size_mb = os.path.getsize(output_path) / (1024 * 1024)
        print(f"✅ Compressed to {output_path} ({size_mb:.1f}MB)")
        return output_path
    
    def extract_node_modules(self, archive_path, extract_to):
        """Extract tar.gz archive to specified directory"""
        print(f"📂 Extracting {archive_path}...")
        
        with tarfile.open(archive_path, 'r:gz') as tar:
            tar.extractall(extract_to)
        
        print(f"✅ Extracted to {extract_to}")
    
    def upload_node_modules(self, project_path):
        """Upload node_modules to Wasabi"""
        node_modules_path = os.path.join(project_path, 'node_modules')
        
        if not os.path.exists(node_modules_path):
            print(f"❌ node_modules not found in {project_path}")
            return False
        
        project_info = self.get_project_info(project_path)
        
        # Create archive
        with tempfile.TemporaryDirectory() as temp_dir:
            archive_name = f"{project_info['name']}-{project_info['version']}-{project_info['hash']}.tar.gz"
            archive_path = os.path.join(temp_dir, archive_name)
            
            self.compress_node_modules(node_modules_path, archive_path)
            
            # Upload to Wasabi
            s3_key = f"node_modules/{archive_name}"
            
            print(f"☁️ Uploading to Wasabi: {s3_key}")
            
            try:
                # Create metadata
                metadata = {
                    'project-name': project_info['name'],
                    'project-version': project_info['version'],
                    'package-hash': project_info['hash'] or '',
                    'upload-date': datetime.now().isoformat(),
                    'local-path': os.path.abspath(project_path)
                }
                
                self.s3.upload_file(
                    archive_path,
                    self.bucket_name,
                    s3_key,
                    ExtraArgs={
                        'Metadata': metadata,
                        'ContentType': 'application/gzip'
                    }
                )
                
                # Save cache info locally
                self.save_cache_info(project_path, {
                    's3_key': s3_key,
                    'archive_name': archive_name,
                    'project_info': project_info,
                    'upload_date': metadata['upload-date']
                })
                
                print(f"✅ Successfully uploaded node_modules for {project_info['name']}")
                print(f"📊 Archive: {archive_name}")
                return True
                
            except Exception as e:
                print(f"❌ Upload failed: {e}")
                return False
    
    def download_node_modules(self, project_path, force=False):
        """Download node_modules from Wasabi"""
        project_info = self.get_project_info(project_path)
        node_modules_path = os.path.join(project_path, 'node_modules')
        
        # Check if we need to download
        if os.path.exists(node_modules_path) and not force:
            cache_info = self.load_cache_info(project_path)
            if cache_info and cache_info['project_info']['hash'] == project_info['hash']:
                print(f"✅ node_modules already up-to-date for {project_info['name']}")
                return True
        
        # Find matching archive in Wasabi
        archive_name = self.find_best_match(project_info)
        
        if not archive_name:
            print(f"❌ No matching node_modules found in Wasabi for {project_info['name']}")
            return False
        
        s3_key = f"node_modules/{archive_name}"
        
        with tempfile.TemporaryDirectory() as temp_dir:
            archive_path = os.path.join(temp_dir, archive_name)
            
            print(f"☁️ Downloading from Wasabi: {s3_key}")
            
            try:
                self.s3.download_file(self.bucket_name, s3_key, archive_path)
                
                # Remove existing node_modules if it exists
                if os.path.exists(node_modules_path):
                    print(f"🗑️ Removing existing node_modules...")
                    shutil.rmtree(node_modules_path)
                
                # Extract archive
                self.extract_node_modules(archive_path, project_path)
                
                print(f"✅ Successfully restored node_modules for {project_info['name']}")
                return True
                
            except Exception as e:
                print(f"❌ Download failed: {e}")
                return False
    
    def find_best_match(self, project_info):
        """Find the best matching archive for the project"""
        try:
            # List all node_modules archives
            response = self.s3.list_objects_v2(
                Bucket=self.bucket_name,
                Prefix='node_modules/'
            )
            
            if 'Contents' not in response:
                return None
            
            best_match = None
            
            for obj in response['Contents']:
                key = obj['Key']
                filename = key.split('/')[-1]
                
                # Try exact hash match first
                if project_info['hash'] and project_info['hash'] in filename:
                    return filename
                
                # Try name and version match
                if project_info['name'] in filename and project_info['version'] in filename:
                    if not best_match:
                        best_match = filename
            
            return best_match
            
        except Exception as e:
            print(f"❌ Error finding matches: {e}")
            return None
    
    def list_cached_modules(self):
        """List all node_modules archives in Wasabi"""
        try:
            response = self.s3.list_objects_v2(
                Bucket=self.bucket_name,
                Prefix='node_modules/'
            )
            
            if 'Contents' not in response:
                print("📦 No node_modules archives found in Wasabi")
                return
            
            print("📦 Node Modules Archives in Wasabi:")
            print("=" * 60)
            
            for obj in response['Contents']:
                key = obj['Key']
                filename = key.split('/')[-1]
                size_mb = obj['Size'] / (1024 * 1024)
                modified = obj['LastModified'].strftime('%Y-%m-%d %H:%M:%S')
                
                # Try to get metadata
                try:
                    metadata_response = self.s3.head_object(Bucket=self.bucket_name, Key=key)
                    metadata = metadata_response.get('Metadata', {})
                    project_name = metadata.get('project-name', 'Unknown')
                    project_version = metadata.get('project-version', 'Unknown')
                    upload_date = metadata.get('upload-date', 'Unknown')
                    
                    print(f"📄 {filename}")
                    print(f"   Project: {project_name} v{project_version}")
                    print(f"   Size: {size_mb:.1f}MB")
                    print(f"   Modified: {modified}")
                    print(f"   Upload Date: {upload_date}")
                    print()
                    
                except:
                    print(f"📄 {filename} ({size_mb:.1f}MB) - {modified}")
                    print()
            
        except Exception as e:
            print(f"❌ Error listing archives: {e}")
    
    def cleanup_old_archives(self, keep_latest=3):
        """Remove old node_modules archives, keeping only the latest versions"""
        try:
            response = self.s3.list_objects_v2(
                Bucket=self.bucket_name,
                Prefix='node_modules/'
            )
            
            if 'Contents' not in response:
                print("📦 No archives to clean up")
                return
            
            # Group by project name
            projects = {}
            
            for obj in response['Contents']:
                key = obj['Key']
                filename = key.split('/')[-1]
                
                try:
                    metadata_response = self.s3.head_object(Bucket=self.bucket_name, Key=key)
                    metadata = metadata_response.get('Metadata', {})
                    project_name = metadata.get('project-name', 'unknown')
                except:
                    # Fallback to filename parsing
                    project_name = filename.split('-')[0] if '-' in filename else 'unknown'
                
                if project_name not in projects:
                    projects[project_name] = []
                
                projects[project_name].append({
                    'key': key,
                    'filename': filename,
                    'modified': obj['LastModified'],
                    'size': obj['Size']
                })
            
            # Sort and remove old archives
            total_deleted = 0
            total_size_saved = 0
            
            for project_name, archives in projects.items():
                if len(archives) <= keep_latest:
                    continue
                
                # Sort by modification date (newest first)
                archives.sort(key=lambda x: x['modified'], reverse=True)
                
                # Keep only the latest N archives
                to_delete = archives[keep_latest:]
                
                print(f"🗑️ Cleaning up {project_name}: removing {len(to_delete)} old archives")
                
                for archive in to_delete:
                    try:
                        self.s3.delete_object(Bucket=self.bucket_name, Key=archive['key'])
                        total_deleted += 1
                        total_size_saved += archive['size']
                        print(f"   Deleted: {archive['filename']}")
                    except Exception as e:
                        print(f"   ❌ Failed to delete {archive['filename']}: {e}")
            
            size_saved_mb = total_size_saved / (1024 * 1024)
            print(f"\n✅ Cleanup complete: {total_deleted} archives deleted ({size_saved_mb:.1f}MB saved)")
            
        except Exception as e:
            print(f"❌ Cleanup failed: {e}")
    
    def save_cache_info(self, project_path, cache_info):
        """Save cache information locally"""
        cache_file = os.path.join(project_path, '.wasabi-node-modules-cache.json')
        try:
            with open(cache_file, 'w') as f:
                json.dump(cache_info, f, indent=2)
        except Exception as e:
            print(f"⚠️ Could not save cache info: {e}")
    
    def load_cache_info(self, project_path):
        """Load cache information from local file"""
        cache_file = os.path.join(project_path, '.wasabi-node-modules-cache.json')
        try:
            with open(cache_file, 'r') as f:
                return json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            return None
    
    def sync_project(self, project_path):
        """Smart sync: upload if local is newer, download if remote is newer"""
        project_info = self.get_project_info(project_path)
        node_modules_path = os.path.join(project_path, 'node_modules')
        
        print(f"🔄 Syncing node_modules for {project_info['name']}...")
        
        # Check if local node_modules exists
        local_exists = os.path.exists(node_modules_path)
        
        # Check if remote archive exists
        remote_archive = self.find_best_match(project_info)
        remote_exists = remote_archive is not None
        
        if not local_exists and not remote_exists:
            print(f"❌ No local or remote node_modules found for {project_info['name']}")
            print("💡 Run 'npm install' first, then upload with --upload")
            return False
        
        if local_exists and not remote_exists:
            print("📤 Local node_modules found, uploading to Wasabi...")
            return self.upload_node_modules(project_path)
        
        if not local_exists and remote_exists:
            print("📥 Remote archive found, downloading from Wasabi...")
            return self.download_node_modules(project_path)
        
        # Both exist - check which is newer
        cache_info = self.load_cache_info(project_path)
        
        if cache_info and cache_info['project_info']['hash'] == project_info['hash']:
            print("✅ Local and remote are in sync")
            return True
        else:
            print("📤 Local package.json changed, uploading updated node_modules...")
            return self.upload_node_modules(project_path)

def main():
    parser = argparse.ArgumentParser(description='Manage node_modules with Wasabi cloud storage')
    parser.add_argument('action', choices=['upload', 'download', 'sync', 'list', 'cleanup'], 
                       help='Action to perform')
    parser.add_argument('--project', '-p', default='.', 
                       help='Project directory (default: current directory)')
    parser.add_argument('--force', '-f', action='store_true', 
                       help='Force download even if local node_modules exists')
    parser.add_argument('--keep', type=int, default=3, 
                       help='Number of archives to keep during cleanup (default: 3)')
    
    args = parser.parse_args()
    
    # Initialize manager
    try:
        manager = WasabiNodeModulesManager()
    except Exception as e:
        print(f"❌ Failed to initialize Wasabi connection: {e}")
        sys.exit(1)
    
    # Execute action
    project_path = os.path.abspath(args.project)
    
    if args.action == 'upload':
        success = manager.upload_node_modules(project_path)
    elif args.action == 'download':
        success = manager.download_node_modules(project_path, force=args.force)
    elif args.action == 'sync':
        success = manager.sync_project(project_path)
    elif args.action == 'list':
        manager.list_cached_modules()
        success = True
    elif args.action == 'cleanup':
        manager.cleanup_old_archives(keep_latest=args.keep)
        success = True
    else:
        print(f"❌ Unknown action: {args.action}")
        success = False
    
    if not success:
        sys.exit(1)
    
    print("🎉 Operation completed successfully!")

if __name__ == '__main__':
    main()
