#!/bin/bash
# Wasabi Node Modules Manager - Shell Wrapper
# Provides convenient commands for managing node_modules with Wasabi cloud storage

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PYTHON_SCRIPT="$SCRIPT_DIR/wasabi_node_modules_manager.py"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Print colored output
print_status() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

print_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Show help
show_help() {
    cat << EOF
🚀 Wasabi Node Modules Manager
=============================

Manage node_modules directories with Wasabi cloud storage for backup,
caching, and team collaboration.

USAGE:
    $0 <command> [options]

COMMANDS:
    upload [project]     Upload node_modules to Wasabi
    download [project]   Download node_modules from Wasabi  
    sync [project]       Smart sync (upload if local newer, download if remote newer)
    list                 List all cached node_modules in Wasabi
    cleanup [keep]       Remove old archives (default: keep 3 latest)
    
    init [project]       Initialize a project for Wasabi node_modules management
    status [project]     Show sync status for a project
    
    help                 Show this help message

OPTIONS:
    project              Project directory (default: current directory)
    keep                 Number of archives to keep during cleanup
    --force, -f          Force download even if local exists
    --all, -a            Process all Node.js projects in workspace

EXAMPLES:
    # Upload current project's node_modules
    $0 upload
    
    # Download node_modules for frontend project
    $0 download ./frontend
    
    # Smart sync current project
    $0 sync
    
    # List all cached modules
    $0 list
    
    # Clean up old archives, keep 5 latest
    $0 cleanup 5
    
    # Check status of all projects
    $0 status --all

SETUP:
    First time setup requires Wasabi credentials:
    ./configure_wasabi_keys.sh

EOF
}

# Check if Wasabi is configured
check_wasabi_config() {
    if [[ ! -f ".env.wasabi" ]]; then
        print_error "Wasabi not configured!"
        print_status "Run: ./configure_wasabi_keys.sh"
        exit 1
    fi
}

# Find all Node.js projects in workspace
find_nodejs_projects() {
    find . -name "package.json" -not -path "./node_modules/*" -exec dirname {} \; | sort
}

# Initialize project for Wasabi management
init_project() {
    local project_dir="${1:-.}"
    project_dir=$(realpath "$project_dir")
    
    print_status "Initializing Wasabi node_modules management for: $project_dir"
    
    if [[ ! -f "$project_dir/package.json" ]]; then
        print_error "No package.json found in $project_dir"
        exit 1
    fi
    
    # Add cache file to .gitignore if not already there
    local gitignore="$project_dir/.gitignore"
    if [[ -f "$gitignore" ]]; then
        if ! grep -q ".wasabi-node-modules-cache.json" "$gitignore"; then
            echo ".wasabi-node-modules-cache.json" >> "$gitignore"
            print_success "Added .wasabi-node-modules-cache.json to .gitignore"
        fi
    else
        echo ".wasabi-node-modules-cache.json" > "$gitignore"
        print_success "Created .gitignore with cache file entry"
    fi
    
    # Create npm scripts for Wasabi management
    local package_json="$project_dir/package.json"
    if command -v jq >/dev/null 2>&1; then
        print_status "Adding npm scripts for Wasabi management..."
        
        # Backup original package.json
        cp "$package_json" "$package_json.backup"
        
        # Add scripts
        jq '.scripts["wasabi:upload"] = "wasabi-node-modules upload"' "$package_json" | \
        jq '.scripts["wasabi:download"] = "wasabi-node-modules download"' | \
        jq '.scripts["wasabi:sync"] = "wasabi-node-modules sync"' > "$package_json.tmp"
        
        mv "$package_json.tmp" "$package_json"
        print_success "Added npm scripts: wasabi:upload, wasabi:download, wasabi:sync"
    else
        print_warning "jq not found - skipping npm scripts setup"
    fi
    
    print_success "Project initialized for Wasabi node_modules management"
    print_status "You can now use: npm run wasabi:sync"
}

# Show status for project(s)
show_status() {
    local project_dir="${1:-.}"
    local show_all="${2:-false}"
    
    if [[ "$show_all" == "true" ]]; then
        print_status "Checking status for all Node.js projects..."
        local projects
        readarray -t projects < <(find_nodejs_projects)
        
        if [[ ${#projects[@]} -eq 0 ]]; then
            print_warning "No Node.js projects found in workspace"
            exit 0
        fi
        
        for proj in "${projects[@]}"; do
            echo ""
            print_status "=== $(basename "$proj") ==="
            show_single_status "$proj"
        done
    else
        show_single_status "$project_dir"
    fi
}

# Show status for a single project
show_single_status() {
    local project_dir="$1"
    project_dir=$(realpath "$project_dir")
    
    if [[ ! -f "$project_dir/package.json" ]]; then
        print_error "No package.json found in $project_dir"
        return 1
    fi
    
    local project_name
    project_name=$(jq -r '.name // "unknown"' "$project_dir/package.json" 2>/dev/null || echo "unknown")
    
    print_status "Project: $project_name ($project_dir)"
    
    # Check local node_modules
    if [[ -d "$project_dir/node_modules" ]]; then
        local size
        size=$(du -sh "$project_dir/node_modules" 2>/dev/null | cut -f1 || echo "unknown")
        print_success "Local node_modules: $size"
    else
        print_warning "Local node_modules: not found"
    fi
    
    # Check cache info
    local cache_file="$project_dir/.wasabi-node-modules-cache.json"
    if [[ -f "$cache_file" ]]; then
        local upload_date
        upload_date=$(jq -r '.upload_date // "unknown"' "$cache_file" 2>/dev/null || echo "unknown")
        print_success "Wasabi cache: available (uploaded: $upload_date)"
    else
        print_warning "Wasabi cache: not found"
    fi
}

# Process all projects
process_all_projects() {
    local command="$1"
    local projects
    readarray -t projects < <(find_nodejs_projects)
    
    if [[ ${#projects[@]} -eq 0 ]]; then
        print_warning "No Node.js projects found in workspace"
        exit 0
    fi
    
    print_status "Found ${#projects[@]} Node.js projects"
    
    for proj in "${projects[@]}"; do
        echo ""
        print_status "=== Processing $(basename "$proj") ==="
        
        case "$command" in
            upload|download|sync)
                python3 "$PYTHON_SCRIPT" "$command" --project "$proj"
                ;;
            *)
                print_error "Command '$command' not supported for --all"
                exit 1
                ;;
        esac
    done
}

# Main command processing
main() {
    # Check for Python dependencies
    if ! python3 -c "import boto3" 2>/dev/null; then
        print_error "Required Python package 'boto3' not found"
        print_status "Install with: pip install boto3 python-dotenv"
        exit 1
    fi
    
    # Parse arguments
    local command="${1:-help}"
    local project="${2:-.}"
    local extra_args=()
    local force=false
    local show_all=false
    
    # Parse options
    while [[ $# -gt 0 ]]; do
        case $1 in
            --force|-f)
                force=true
                extra_args+=("--force")
                shift
                ;;
            --all|-a)
                show_all=true
                shift
                ;;
            --keep)
                extra_args+=("--keep" "$2")
                shift 2
                ;;
            -*)
                print_error "Unknown option: $1"
                show_help
                exit 1
                ;;
            *)
                shift
                ;;
        esac
    done
    
    # Execute command
    case "$command" in
        help|--help|-h)
            show_help
            ;;
        
        upload|download|sync)
            check_wasabi_config
            if [[ "$show_all" == "true" ]]; then
                process_all_projects "$command"
            else
                python3 "$PYTHON_SCRIPT" "$command" --project "$project" "${extra_args[@]}"
            fi
            ;;
        
        list)
            check_wasabi_config
            python3 "$PYTHON_SCRIPT" list
            ;;
        
        cleanup)
            check_wasabi_config
            local keep="${2:-3}"
            python3 "$PYTHON_SCRIPT" cleanup --keep "$keep"
            ;;
        
        init)
            init_project "$project"
            ;;
        
        status)
            check_wasabi_config
            show_status "$project" "$show_all"
            ;;
        
        *)
            print_error "Unknown command: $command"
            show_help
            exit 1
            ;;
    esac
}

# Run main function with all arguments
main "$@"
